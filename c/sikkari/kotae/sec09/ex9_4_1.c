// for文で、*を横に10個、縦に3行表示プログラム
#include <stdio.h>

int main(void)
{
    for (int i = 1; i <= 10; i++) 
        printf("*");
    printf("\n");

    for (int i = 1; i <= 10; i++) 
        printf("*");
    printf("\n");

    for (int i = 1; i <= 10; i++) 
        printf("*");
    printf("\n");

    return 0;
}